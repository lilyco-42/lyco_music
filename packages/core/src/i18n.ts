const RAW: Record<Locale, Dict> = {
  'zh-CN': ZH_CN,
  'zh-TW': {},
  'en-US': EN_US,
  'ko-KR': KO_KR,
}

let twCache: Dict | null = null
function traditionalDict(): Dict {
  if (twCache) return twCache
  const out: Dict = {}
  for (const k of Object.keys(ZH_CN)) out[k] = toTraditional(ZH_CN[k]!)
  twCache = out
  return out
}

export function dictFor(loc: Locale): Dict {
  if (loc === 'zh-TW') return traditionalDict()
  return RAW[loc] ?? ZH_CN
}

export function translate(key: string, loc: Locale = 'zh-CN', fallback?: string): string {
  const hit = dictFor(loc)[key]
  if (hit) return hit
  const zh = ZH_CN[key]
  if (zh) return zh
  return fallback ?? key
}

export function translateFormat(
  key: string,
  loc: Locale = 'zh-CN',
  params?: Record<string, string | number>,
  fallback?: string,
): string {
  let out = translate(key, loc, fallback)
  if (!params) return out
  for (const [k, v] of Object.entries(params)) out = out.split('{' + k + '}').join(String(v))
  return out
}

